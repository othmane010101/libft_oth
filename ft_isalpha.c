int	ft_isalpha(char c)
{
	if (('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z'))
		return (1);
	return (0);
}

#include <stdio.h>
int main(void)
{
    printf("%d", ft_isalpha(-1));
    return (0);
}
